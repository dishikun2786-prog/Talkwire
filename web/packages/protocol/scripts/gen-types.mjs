// Generates TypeScript types for the wire frames from contract/protocol/schema.
//
//   node scripts/gen-types.mjs           write src/generated/*.ts
//   node scripts/gen-types.mjs --check   exit 1 if they are out of date
//
// The schemas are written in one style: the client schema is a single object
// whose allOf holds one if/then per action; the server schema is an anyOf of
// an action family (if/then per action, each a oneOf of variants), a type
// family (if/then per type) and a generic error frame. This generator knows
// exactly that style and stops on anything else, so a schema written another
// way fails here instead of producing quietly wrong types.
//
// Names: client action x -> XRequest; server action x -> XReply (code 200)
// and XPush (no code); server type x -> XFrame; the shared error -> ErrorReply;
// $defs/x -> X.

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkg = resolve(here, "..");
const schemaDir = resolve(pkg, "../../../contract/protocol/schema");
const outDir = join(pkg, "src/generated");
const check = process.argv.includes("--check");

const HEADER = "// Generated by packages/protocol/scripts/gen-types.mjs from contract/protocol/schema. Do not edit.\n";

function fail(msg) {
  throw new Error("gen-types: " + msg);
}

export function pascal(s) {
  return s
    .split(/[^A-Za-z0-9]+/)
    .filter(Boolean)
    .map((w) => w[0].toUpperCase() + w.slice(1))
    .join("");
}

const IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/;
const KNOWN = new Set([
  "type", "properties", "required", "additionalProperties", "items", "enum", "const", "$ref",
  "oneOf", "anyOf", "description", "pattern", "minLength", "minimum", "minItems", "not", "title",
]);

function doc(description, indent) {
  if (!description) return "";
  const lines = description.split("\n");
  return lines.length === 1
    ? `${indent}/** ${description.replace(/\*\//g, "*\\/")} */\n`
    : `${indent}/**\n${lines.map((l) => `${indent} * ${l}`).join("\n")}\n${indent} */\n`;
}

/** The TypeScript type of one schema node. */
function tsType(node, indent) {
  if (node === true || (node && typeof node === "object" && Object.keys(node).length === 0)) return "unknown";
  if (!node || typeof node !== "object") fail("unexpected schema node " + JSON.stringify(node));
  for (const k of Object.keys(node)) if (!KNOWN.has(k)) fail(`unsupported keyword "${k}" in ${JSON.stringify(node).slice(0, 120)}`);
  if (node.$ref) {
    const m = /^#\/\$defs\/([A-Za-z0-9_]+)$/.exec(node.$ref);
    if (!m) fail("unsupported $ref " + node.$ref);
    return pascal(m[1]);
  }
  if (node.not) {
    // The only use is "any value but null" (dialog extra).
    if (node.not.type !== "null" || Object.keys(node.not).length !== 1 || node.type) fail("unsupported not: " + JSON.stringify(node));
    return "NonNullable<unknown>";
  }
  if ("const" in node) return JSON.stringify(node.const);
  if (node.enum) return node.enum.map((v) => JSON.stringify(v)).join(" | ");
  const union = node.oneOf ?? node.anyOf;
  if (union) return union.map((u) => wrap(tsType(u, indent))).join(" | ");
  const types = Array.isArray(node.type) ? node.type : [node.type];
  return types.map((t) => {
    switch (t) {
      case "string": return "string";
      case "integer":
      case "number": return "number";
      case "boolean": return "boolean";
      case "null": return "null";
      case "array": return node.items ? `${wrap(tsType(node.items, indent))}[]` : "unknown[]";
      case "object":
      case undefined:
        if (node.properties) return objectLiteral(node, indent);
        if (t === undefined) fail("schema node without a type: " + JSON.stringify(node).slice(0, 120));
        return "Record<string, unknown>";
      default: fail("unsupported type " + t);
    }
  }).join(" | ");
}

function wrap(t) {
  return /[|&]/.test(t) && !t.startsWith("{") ? `(${t})` : t;
}

function fields(node, indent) {
  const required = new Set(node.required ?? []);
  let out = "";
  for (const [key, prop] of Object.entries(node.properties ?? {})) {
    const name = IDENT.test(key) ? key : JSON.stringify(key);
    out += doc(prop.description, indent);
    out += `${indent}${name}${required.has(key) ? "" : "?"}: ${tsType(prop, indent + "  ")};\n`;
  }
  return out;
}

function objectLiteral(node, indent) {
  return `{\n${fields(node, indent + "  ")}${indent}}`;
}

function iface(name, node, description) {
  if (node.type !== "object" || !node.properties) fail(`${name} is not an object schema`);
  return `${doc(description ?? node.description, "")}export interface ${name} {\n${fields(node, "  ")}}\n`;
}

function defs(schema, names) {
  let out = "";
  for (const [key, node] of Object.entries(schema.$defs ?? {})) {
    const name = pascal(key);
    names.add(name);
    out += "\n" + (node.type === "object" && node.properties
      ? iface(name, node)
      : `${doc(node.description, "")}export type ${name} = ${tsType(node, "")};\n`);
  }
  return out;
}

function branch(entry, field) {
  const v = entry?.if?.properties?.[field]?.const;
  if (typeof v !== "string" || !entry.then) fail(`allOf entry is not an if/then on ${field}: ${JSON.stringify(entry).slice(0, 160)}`);
  return [v, entry.then];
}

/** The generic error frame every action can answer with. */
function isGenericError(v) {
  const p = v.properties ?? {};
  return p.code?.minimum === 400 && p.action?.type === "string" && !("const" in (p.action ?? {}));
}

export function generateClient(schema) {
  const names = new Set();
  let out = HEADER;
  out += "\n/** Every action a client sends. */\n";
  out += `export type ClientAction = ${schema.properties.action.enum.map((a) => JSON.stringify(a)).join(" | ")};\n`;
  out += defs(schema, names);
  const members = [];
  for (const entry of schema.allOf) {
    const [action, then] = branch(entry, "action");
    const name = pascal(action) + "Request";
    if (names.has(name)) fail("duplicate name " + name);
    names.add(name);
    members.push(name);
    out += "\n" + iface(name, then);
  }
  out += `\n/** A frame the client sends, discriminated by \`action\`. */\nexport type ClientFrame =\n${members.map((m) => `  | ${m}`).join("\n")};\n`;
  return { text: out, names };
}

export function generateServer(schema) {
  const names = new Set();
  let out = HEADER;
  const [actions, types, error] = schema.anyOf;
  if (!actions?.allOf || !types?.allOf || !error || !isGenericError(error)) fail("server schema is not anyOf [actions, types, error]");
  out += "\n/** Every `action` the server sends. */\n";
  out += `export type ServerAction = ${actions.properties.action.enum.map((a) => JSON.stringify(a)).join(" | ")};\n`;
  out += "\n/** Every `type` the server sends. */\n";
  out += `export type ServerType = ${types.properties.type.enum.map((a) => JSON.stringify(a)).join(" | ")};\n`;
  out += defs(schema, names);
  out += "\n" + iface("ErrorReply", error, "The error answer to any action: `code` 400 or more (section 4.1).");
  names.add("ErrorReply");

  const members = [];
  const add = (name, node) => {
    if (names.has(name)) fail("duplicate name " + name);
    names.add(name);
    members.push(name);
    out += "\n" + iface(name, node);
  };
  for (const entry of actions.allOf) {
    const [action, then] = branch(entry, "action");
    const variants = (then.oneOf ?? [then]).filter((v) => !isGenericError(v));
    const replies = variants.filter((v) => "const" in (v.properties?.code ?? {}));
    const pushes = variants.filter((v) => !("const" in (v.properties?.code ?? {})));
    const named = (list, suffix) => list.forEach((v, i) => add(pascal(action) + suffix + (list.length > 1 ? String(i + 1) : ""), v));
    named(replies, "Reply");
    named(pushes, "Push");
  }
  for (const entry of types.allOf) {
    const [type, then] = branch(entry, "type");
    const variants = then.oneOf ?? [then];
    variants.forEach((v, i) => add(pascal(type) + "Frame" + (variants.length > 1 ? String(i + 1) : ""), v));
  }
  out += `\n/** A frame the server sends: an action frame, a type frame or an error (section 3.1). */\nexport type ServerFrame =\n${[...members, "ErrorReply"].map((m) => `  | ${m}`).join("\n")};\n`;
  return { text: out, names };
}

function main() {
  const client = generateClient(JSON.parse(readFileSync(join(schemaDir, "client-frames.schema.json"), "utf8")));
  const server = generateServer(JSON.parse(readFileSync(join(schemaDir, "server-frames.schema.json"), "utf8")));
  for (const n of client.names) if (server.names.has(n)) fail(`${n} is generated for both the client and the server schema`);
  const files = { "client-frames.ts": client.text, "server-frames.ts": server.text };
  let stale = [];
  for (const [file, text] of Object.entries(files)) {
    const path = join(outDir, file);
    const current = existsSync(path) ? readFileSync(path, "utf8") : null;
    if (current === text) continue;
    if (check) stale.push(file);
    else {
      mkdirSync(outDir, { recursive: true });
      writeFileSync(path, text);
      console.log("wrote src/generated/" + file);
    }
  }
  if (check && stale.length) {
    console.error("out of date, run npm run gen: " + stale.join(", "));
    process.exit(1);
  }
  if (check) console.log("generated types are up to date");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
